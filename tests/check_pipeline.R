source("scripts/pipeline.R")
run_pipeline(".")
a <- read.csv("results/data_audit.csv")
s <- read.csv("results/split_summary.csv")
m <- read.csv("results/test_metrics.csv")
stopifnot(a$value[a$measure=="rows"] == 100000)
stopifnot(a$value[a$measure=="columns"] == 39)
stopifnot(a$value[a$measure=="missing_county"] == 35991)
stopifnot(a$value[a$measure=="discovery_date_year_mismatch"] == 2)
stopifnot(identical(s$split,c("train_1992_2007","validation_2008_2011","test_2012_2015")))
stopifnot(all(c("prevalence","season","logistic","random_forest") %in% m$model))
stopifnot(all(c("roc_auc","average_precision","brier","tp","fp","fn","tn") %in% names(m)))
stopifnot(all(is.finite(m$roc_auc)), all(is.finite(m$brier)))
test_prevalence <- s$prevalence[s$split=="test_2012_2015"]
stopifnot(abs(m$average_precision[m$model=="prevalence"]-test_prevalence) < 1e-10)
stopifnot(sum(m[c("tp","fp","fn","tn")][m$model=="random_forest",]) == s$n[s$split=="test_2012_2015"])
cat("Pipeline checks passed.\n")
